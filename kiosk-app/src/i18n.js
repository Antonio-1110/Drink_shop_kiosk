export function translate(lang, key, vars = {}) {
    const table = STRINGS[lang] ?? STRINGS.en;
    // Chinese has no singular form, so only a table that has the key itself is asked for 'key_one'
    const own = table[key] !== undefined ? table : STRINGS.en;
    const text = (vars.count === 1 ? own[`${key}_one`] : undefined) ?? own[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
}

// without a provider (e.g. in tests) the kiosk is in English
export const LanguageContext = createContext({ lang: 'en', setLang: () => {} });

export const useLanguage = () => useContext(LanguageContext);

export function useT() {
    const { lang } = useContext(LanguageContext);
    return useCallback((key, vars) => translate(lang, key, vars), [lang]);
}
